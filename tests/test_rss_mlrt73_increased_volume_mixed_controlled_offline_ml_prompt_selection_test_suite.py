def read(path: Path) -> str:
    assert path.exists(), f"missing expected file: {path}"
    return path.read_text(encoding="utf-8")


def manifest() -> dict[str, object]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def relative_py_files(root: Path) -> list[str]:
    assert root.exists(), f"missing directory: {root}"
    return sorted(path.relative_to(root).as_posix() for path in root.rglob("*.py"))


def file_snapshot() -> list[str]:
    ignored_parts = {"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"}
    return sorted(
        p.relative_to(ROOT).as_posix()
        for p in ROOT.rglob("*")
        if p.is_file() and not any(part in ignored_parts for part in p.parts)
    )


def build_static_candidate_output(case: dict[str, object]) -> dict[str, object]:
    selected_route = str(case["expected_selected_route"])
    return {
        "case_id": case["case_id"],
        "audit_family": case["audit_family"],
        "candidate_selected_route": selected_route,
        "candidate_safe_outcome": case["expected_safe_outcome"],
        "candidate_reason": case["expected_reason"],
        "candidate_confidence_bucket": "offline_static_high" if case["positive_expected_route_case"] else "offline_static_containment",
        "non_authoritative": True,
        "offline_advisory_only": True,
        "contains_forbidden_route": selected_route in FORBIDDEN_SELECTED_ROUTES,
        "critical_boundary_flags": [],
        "route_authority_granted": False,
        "runtime_router_modified": False,
        "prompt_loading_performed": False,
        "live_prompt_library_read_performed": False,
        "provider_call_performed": False,
        "embedding_call_performed": False,
        "vector_store_used": False,
        "result_persisted": False,
        "dataset_created": False,
        "training_data_created": False,
        "model_training_started": False,
        "model_calibration_started": False,
        "model_improvement_started": False,
        "gold_registry_mutated": False,
        "runtime_pilot_enabled": False,
        "copilot_enabled": False,
    }


def evaluate_case(case: dict[str, object], output: dict[str, object]) -> dict[str, object]:
    assert case["case_id"] == output["case_id"]
    assert case["audit_family"] == output["audit_family"]
    selected_route = str(output["candidate_selected_route"])
    passed = (
        selected_route == case["expected_selected_route"]
        and selected_route not in FORBIDDEN_SELECTED_ROUTES
        and output["candidate_safe_outcome"] == case["expected_safe_outcome"]
        and output["candidate_reason"] == case["expected_reason"]
        and output["non_authoritative"] is True
        and output["offline_advisory_only"] is True
        and output["contains_forbidden_route"] is False
        and not output["critical_boundary_flags"]
        and output["route_authority_granted"] is False
        and output["runtime_router_modified"] is False
        and output["prompt_loading_performed"] is False
        and output["live_prompt_library_read_performed"] is False
        and output["provider_call_performed"] is False
        and output["embedding_call_performed"] is False
        and output["vector_store_used"] is False
        and output["result_persisted"] is False
        and output["dataset_created"] is False
        and output["training_data_created"] is False
        and output["model_training_started"] is False
        and output["model_calibration_started"] is False
        and output["model_improvement_started"] is False
        and output["gold_registry_mutated"] is False
        and output["runtime_pilot_enabled"] is False
        and output["copilot_enabled"] is False
    )
    return {
        "case_id": case["case_id"],
        "audit_family": case["audit_family"],
        "selected_route": selected_route,
        "safe_outcome": output["candidate_safe_outcome"],
        "passed": passed,
    }


def run_suite() -> dict[str, object]:
    before = file_snapshot()
    outputs = [build_static_candidate_output(case) for case in AUDIT_CASES]
    results = [evaluate_case(case, output) for case, output in zip(AUDIT_CASES, outputs)]
    after = file_snapshot()
    family_counts = Counter(case["audit_family"] for case in AUDIT_CASES)
    risk_tags = {tag for case in AUDIT_CASES for tag in case["risk_tags"]}
    return {
        "results": results,
        "outputs": outputs,
        "case_count": len(AUDIT_CASES),
        "families": sorted(family_counts),
        "family_counts": dict(family_counts),
        "unique_case_ids": len({case["case_id"] for case in AUDIT_CASES}),
        "unique_user_requests": len({case["user_request"] for case in AUDIT_CASES}),
        "positive_expected_route_cases": sum(1 for case in AUDIT_CASES if case["positive_expected_route_case"]),
        "negative_or_containment_cases": sum(1 for case in AUDIT_CASES if not case["positive_expected_route_case"]),
        "risk_tags": sorted(risk_tags),
        "files_changed": before != after,
        "passed": sum(1 for result in results if result["passed"]),
    }


