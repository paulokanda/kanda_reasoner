def build_module_summary(
    path: Path,
    module_id: str,
    tree: ast.Module,
    source_lines: list[str],
    ai_config: "AIConfig | None" = None,
) -> ModuleSummary:
    """Build a :class:`ModuleSummary` for *path*, using AI when available.

    This is the entry point called once per file before per-symbol processing
    begins.  When *ai_config* is ``None`` or the LLM call fails, a heuristic
    summary is returned and ``ai_generated`` will be ``False``.

    Parameters
    ----------
    path : Path
        Filesystem path to the Python module.
    module_id : str
        Dotted module identifier (e.g. ``"mypackage.utils"``).
    tree : ast.Module
        Parsed AST of the module.
    source_lines : list[str]
        Raw lines of the module source file.
    ai_config : AIConfig, optional
        When provided, an LLM call is made for richer context.

    Returns
    -------
    ModuleSummary
        Fully populated summary with class profiles and AI-generated prose.
    """
    classes, public_functions, constants = _extract_module_structure(tree)

    # Always build the heuristic first as the safe fallback.
    heuristic_one_liner = _heuristic_summary(path, module_id, tree)
    base = ModuleSummary(
        module_id=module_id,
        one_liner=heuristic_one_liner,
        classes=classes,
        public_functions=public_functions,
        constants=constants,
        ai_generated=False,
    )

    if ai_config is None:
        return base

    # --- LLM call ---
    prompt = _build_module_summary_prompt(
        path, module_id, source_lines, classes, public_functions, constants
    )
    payload = json.dumps({
        "model": ai_config.model,
        "max_tokens": 256,           # summaries are short
        "temperature": 0.05,         # near-deterministic
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are a senior Python architect. "
                    "Analyse the module structure shown and respond ONLY with "
                    "a JSON object containing 'one_liner' and 'paragraph' keys. "
                    "No prose, no markdown, no code blocks."
                ),
            },
            {"role": "user", "content": prompt},
        ],
    }).encode("utf-8")

    endpoint = ai_config.base_url.rstrip("/") + "/chat/completions"
    req = urllib.request.Request(
        endpoint,
        data=payload,
        method="POST",
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )

    try:
        with urllib.request.urlopen(req, timeout=min(ai_config.timeout_seconds, 20.0)) as resp:
            body = resp.read().decode("utf-8")
        data = json.loads(body)
        raw_text = data["choices"][0]["message"]["content"].strip()

        # Strip accidental markdown fences.
        if raw_text.startswith("```"):
            raw_text = "\n".join(
                line for line in raw_text.splitlines()
                if not line.startswith("```")
            ).strip()

        parsed = json.loads(raw_text)
        one_liner = str(parsed.get("one_liner", "")).strip()
        paragraph = str(parsed.get("paragraph", "")).strip()

        if not one_liner:
            return base

        # Ensure one_liner ends with a period.
        if one_liner and not one_liner.endswith("."):
            one_liner += "."

        return ModuleSummary(
            module_id=module_id,
            one_liner=one_liner,
            purpose_paragraph=paragraph,
            classes=classes,
            public_functions=public_functions,
            constants=constants,
            ai_generated=True,
        )

    except Exception:
        # Any failure (network, parse, key error) → return heuristic silently.
        return base


def get_class_profile(summary: ModuleSummary, class_name: str) -> ClassProfile | None:
    """Look up a :class:`ClassProfile` by name from a :class:`ModuleSummary`.

    Parameters
    ----------
    summary : ModuleSummary
        The module summary containing profiled classes.
    class_name : str
        Simple class name to look up.

    Returns
    -------
    ClassProfile or None
        The matching profile, or ``None`` if not found.
    """
    for c in summary.classes:
        if c.name == class_name:
            return c
    return None
